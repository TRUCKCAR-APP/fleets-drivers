-- Cada posición recibida (en vivo por WebSocket o sincronizada desde la cola offline de la PWA). recorded_at es la
-- hora del dispositivo: un lote que llega tarde queda en su lugar cronológico.
CREATE TABLE IF NOT EXISTS position_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id       VARCHAR(64)      NOT NULL,
    load_id         BIGINT,
    latitude        DOUBLE PRECISION NOT NULL,
    longitude       DOUBLE PRECISION NOT NULL,
    speed_kmh       DOUBLE PRECISION,
    heading         DOUBLE PRECISION,
    recorded_at     TIMESTAMPTZ(6)   NOT NULL,
    received_at     TIMESTAMPTZ(6)   NOT NULL DEFAULT now(),
    source          VARCHAR(10)      NOT NULL,
    client_event_id UUID,
    CONSTRAINT position_history_source_check CHECK (source IN ('LIVE', 'OFFLINE'))
);

CREATE INDEX IF NOT EXISTS idx_position_history_driver_time ON position_history (driver_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_position_history_load_time ON position_history (load_id, recorded_at)
    WHERE load_id IS NOT NULL;

-- Registro de eventos offline ya procesados: la clave (driver_id, client_event_id) hace que un lote reenviado
-- (respuesta perdida, reintento de la PWA) no duplique posiciones (INSERT ... ON CONFLICT DO NOTHING).
CREATE TABLE IF NOT EXISTS ingested_events (
    driver_id       VARCHAR(64)    NOT NULL,
    client_event_id UUID           NOT NULL,
    kind            VARCHAR(40)    NOT NULL,
    seq             BIGINT,
    occurred_at     TIMESTAMPTZ(6) NOT NULL,
    received_at     TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    status          VARCHAR(10)    NOT NULL,
    reason          VARCHAR(500),
    PRIMARY KEY (driver_id, client_event_id),
    CONSTRAINT ingested_events_status_check CHECK (status IN ('APPLIED', 'REJECTED'))
);
